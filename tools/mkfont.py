#!/usr/bin/env python3
"""Generates source/font.h: two anti-aliased, proportional font atlases for the
GX menu UI (a small one for body text, a large one for titles and big digits).

Usage: python3 tools/mkfont.py [regular.ttf] [bold.ttf] > source/font.h
Default fonts: Noto Sans Medium / Bold (SIL Open Font License).

Each atlas is an IA8 texture (2 bytes per texel: alpha, intensity), pre-swizzled
into the 4x4 tiles GX reads. Every glyph sits in its own cell with a 1-texel
empty border, so linear filtering never picks up a neighbouring glyph.
Per glyph we store the advance (in 1/8 px) and the x offset of its cell
relative to the pen position, which is what makes the text proportional.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126

# name, size in px, atlas width, baseline target (px below the text's y)
FONTS = [
    ("SMALL", 17, 256, 14, 0),   # index into the font file list
    ("LARGE", 33, 512, 28, 1),
]


def next_pow2(v):
    p = 1
    while p < v:
        p <<= 1
    return p


def build(path, size, atlas_w):
    font = ImageFont.truetype(path, size)
    boxes, advs = {}, {}
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        boxes[c] = font.getbbox(ch, anchor="ls")
        advs[c] = font.getlength(ch)
    asc = max(-b[1] for b in boxes.values())
    desc = max(b[3] for b in boxes.values())
    ink_w = max(b[2] - b[0] for b in boxes.values())
    cell_w, cell_h = ink_w + 2, asc + desc + 2
    base_row = asc + 1
    cols = atlas_w // cell_w
    rows = (LAST - FIRST + cols) // cols
    atlas_h = next_pow2(rows * cell_h)

    img = Image.new("L", (atlas_w, atlas_h), 0)
    xoffs = []
    for c in range(FIRST, LAST + 1):
        i = c - FIRST
        cx, cy = (i % cols) * cell_w, (i // cols) * cell_h
        x0 = boxes[c][0]
        cell = Image.new("L", (cell_w, cell_h), 0)
        ImageDraw.Draw(cell).text((1 - x0, base_row), chr(c), font=font, fill=255, anchor="ls")
        img.paste(cell, (cx, cy))
        xoffs.append(x0 - 1)

    px = img.load()
    data = bytearray()
    for ty in range(0, atlas_h, 4):
        for tx in range(0, atlas_w, 4):
            for y in range(4):
                for x in range(4):
                    data += bytes((px[tx + x, ty + y], 255))   # alpha, intensity
    advs8 = [round(advs[c] * 8) for c in range(FIRST, LAST + 1)]
    return dict(cell_w=cell_w, cell_h=cell_h, cols=cols, atlas_w=atlas_w, atlas_h=atlas_h,
                base_row=base_row, data=data, adv=advs8, xoff=xoffs, img=img)


def main():
    files = [a for a in sys.argv[1:] if not a.startswith("--")][:2] or ["/usr/share/fonts/noto/NotoSans-Medium.ttf",
                              "/usr/share/fonts/noto/NotoSans-Bold.ttf"]
    if len(files) == 1:
        files.append(files[0])
    out = []
    out.append("// GENERATED by tools/mkfont.py -- do not edit by hand.")
    out.append("// Font: Noto Sans (SIL Open Font License 1.1).")
    out.append("// IA8 atlases (bytes per texel: alpha, intensity), pre-swizzled into GX 4x4 tiles.")
    out.append("#ifndef UI_FONT_H\n#define UI_FONT_H\n")
    out.append("#define UI_FONT_FIRST_CHAR %d\n#define UI_FONT_LAST_CHAR %d\n" % (FIRST, LAST))
    for name, size, aw, baseline, fi in FONTS:
        f = build(files[fi], size, aw)
        if "--preview" in sys.argv:
            f["img"].save("font_%s.png" % name.lower())
        p = "UI_FONT_" + name
        out.append("// %s: %d px, from %s" % (name, size, files[fi].split("/")[-1]))
        for k, v in (("CELL_W", f["cell_w"]), ("CELL_H", f["cell_h"]), ("COLS", f["cols"]),
                     ("ATLAS_W", f["atlas_w"]), ("ATLAS_H", f["atlas_h"]),
                     ("BASE_ROW", f["base_row"]), ("BASELINE", baseline), ("LINE_H", baseline + baseline // 7)):
            out.append("#define %s_%s %d" % (p, k, v))
        lo = name.lower()
        out.append("static const unsigned short ui_font_%s_adv8[] = {%s};" % (lo, ",".join(map(str, f["adv"]))))
        out.append("static const signed char ui_font_%s_xoff[] = {%s};" % (lo, ",".join(map(str, f["xoff"]))))
        out.append("static const unsigned char ui_font_%s_atlas[%d] __attribute__((aligned(32))) = {" % (lo, len(f["data"])))
        d = f["data"]
        for i in range(0, len(d), 32):
            out.append(",".join(map(str, d[i:i + 32])) + ",")
        out.append("};\n")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
